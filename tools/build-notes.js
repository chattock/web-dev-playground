#!/usr/bin/env node
/* Turns content/notes/NNN.json (own-words lecture notes) into data/notes/sNN.js,
   one file per section, each line: PG.notes('<lesson id>', '<html>').
   Lesson ids come from data/index.js (built by tools/manifest.js) so notes
   attach to whatever id a lecture's lesson uses.
   Usage: node tools/build-notes.js */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const NOTES = path.join(ROOT, 'content', 'notes');
const OUT = path.join(ROOT, 'data', 'notes');

const esc = s => String(s == null ? '' : s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
// inline formatting: `code`, and the "(Extra) " marker
function rich(s) {
  s = esc(s);
  let extra = false;
  if (s.startsWith('(Extra) ')) { extra = true; s = s.slice(8); }
  s = s.replace(/`([^`]+)`/g, '<code>$1</code>');
  return (extra ? '<span class="extra">Extra:</span> ' : '') + s;
}
const LANG = { javascript: 'js', js: 'js', html: 'html', css: 'css', bash: 'sh', shell: 'sh', sh: 'sh', json: 'json', sql: 'sql', jsx: 'jsx', motoko: 'mo', text: 'txt', ejs: 'ejs', plaintext: 'txt' };
function codeBlock(code, lang, caption) {
  const l = LANG[(lang || '').toLowerCase()] || 'txt';
  return (caption ? `<p class="caption">${rich(caption)}</p>` : '') + `<pre data-lang="${l}">${esc(code)}</pre>`;
}

function render(n) {
  const parts = [];
  if (n.summary) parts.push(`<p class="summary">${rich(n.summary)}</p>`);
  (n.concepts || []).forEach(c => {
    if (c.heading) parts.push(`<h3>${rich(c.heading)}</h3>`);
    if (c.points && c.points.length) parts.push(`<ul>${c.points.map(p => `<li>${rich(p)}</li>`).join('')}</ul>`);
  });
  if (n.code_examples && n.code_examples.length) {
    parts.push('<h2>Code examples</h2>');
    n.code_examples.forEach(ex => { if (ex.code) parts.push(codeBlock(ex.code, ex.language, ex.caption)); });
  }
  const t = n.task;
  if (t) {
    parts.push(`<h2>The task${t.name ? `: ${rich(t.name)}` : ''}</h2>`);
    parts.push('<div class="task-box">');
    if (t.starting_point) parts.push(`<p><b>Starting point:</b> ${rich(t.starting_point)}</p>`);
    if (t.goal) parts.push(`<p><b>Goal:</b> ${rich(t.goal)}</p>`);
    if (t.steps && t.steps.length) parts.push(`<p><b>Steps</b></p><ol>${t.steps.map(s => `<li>${rich(s)}</li>`).join('')}</ol>`);
    if (t.expected_result) parts.push(`<p><b>Expected result:</b> ${rich(t.expected_result)}</p>`);
    parts.push('</div>');
    if (t.solution_code && t.solution_code.code) parts.push(codeBlock(t.solution_code.code, t.solution_code.language, 'Solution'));
  }
  if (n.pitfalls && n.pitfalls.length) {
    parts.push('<h2>Common mistakes</h2>');
    parts.push(`<ul>${n.pitfalls.map(p => `<li>${rich(p)}</li>`).join('')}</ul>`);
  }
  return parts.join('\n');
}

function main() {
  // lesson id per lecture index, from the manifest if it exists
  const ids = {};
  const idx = path.join(ROOT, 'data', 'index.js');
  if (fs.existsSync(idx)) {
    const src = fs.readFileSync(idx, 'utf8');
    const PG = { index: list => list.forEach(l => { if (l.index && !l.sub) ids[l.index] = l.id; }) };
    new Function('PG', src)(PG);
  }
  const bySection = {};
  fs.readdirSync(NOTES).filter(f => f.endsWith('.json')).sort().forEach(f => {
    const n = JSON.parse(fs.readFileSync(path.join(NOTES, f), 'utf8'));
    const sec = 's' + String(parseInt(n.section, 10)).padStart(2, '0');
    const id = ids[n.index] || `l${String(n.index).padStart(3, '0')}`;
    (bySection[sec] = bySection[sec] || []).push({ id, html: render(n) });
  });
  fs.mkdirSync(OUT, { recursive: true });
  let count = 0;
  Object.keys(bySection).sort().forEach(sec => {
    const lines = [`/* Notes for ${sec} — generated by tools/build-notes.js from content/notes. Do not edit by hand. */`];
    bySection[sec].forEach(({ id, html }) => { lines.push(`PG.notes(${JSON.stringify(id)}, ${JSON.stringify(html)});`); count++; });
    fs.writeFileSync(path.join(OUT, sec + '.js'), lines.join('\n') + '\n');
  });
  console.log(`wrote notes for ${count} lectures into ${Object.keys(bySection).length} files`);
}
main();
