#!/usr/bin/env node
/* Builds data/index.js: one stub per lesson so the sidebar can list every
   lecture before any section file is loaded. Reads every data/sNN.js by
   evaluating it with a stub PG. Also warns about lectures with no lesson.
   Usage: node tools/manifest.js */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'data');

function loadLessons() {
  const lessons = [];
  fs.readdirSync(DATA).filter(f => /^s\d\d(-2)?\.js$/.test(f)).sort().forEach(f => {
    const src = fs.readFileSync(path.join(DATA, f), 'utf8');
    const PG = { add: l => lessons.push(Object.assign({ _file: f }, l)), notes() {}, index() {}, registerKit() {} };
    try { new Function('PG', src)(PG); } catch (e) { console.error(`${f}: ${e.message}`); process.exitCode = 1; }
  });
  return lessons;
}

function main() {
  const lessons = loadLessons();
  const seen = new Set(), seenIdx = new Set();
  const stubs = lessons.map(l => {
    if (seen.has(l.id)) { console.error(`duplicate lesson id ${l.id} in ${l._file}`); process.exitCode = 1; }
    seen.add(l.id);
    const key = l.index != null ? String(l.index) + (l.sub || '') : null;
    if (key) { if (seenIdx.has(key)) { console.error(`lecture ${key} has two lessons (${l.id})`); process.exitCode = 1; } seenIdx.add(key); }
    const names = Object.keys(l.files || {});
    const kind = l.kind || (l.layout === 'js' || (names.length === 1 && names[0] === 'js') ? 'js' : 'build');
    return { id: l.id, index: l.index, sub: l.sub || '', section: l.section, slug: l.slug, title: l.title, kind, minutes: l.minutes, project: !!l.project };
  }).sort((a, b) => ((a.index || 9999) - (b.index || 9999)) || a.sub.localeCompare(b.sub));
  const manifest = path.join(ROOT, 'content', 'manifest.txt');
  if (fs.existsSync(manifest)) {
    const missing = [];
    fs.readFileSync(manifest, 'utf8').split('\n').forEach(line => {
      if (!line || line.startsWith('#')) return;
      const [i, , title] = line.split('|'); if (!seenIdx.has(String(Number(i)))) missing.push(`${i} ${title}`);
    });
    if (missing.length) console.log(`${missing.length} lectures have no lesson yet:\n  ` + missing.join('\n  '));
  }
  const out = `/* Generated by tools/manifest.js — do not edit. One stub per lesson. */\nPG.index(${JSON.stringify(stubs, null, 0).replace(/\},\{/g, '},\n{')});\n`;
  fs.writeFileSync(path.join(DATA, 'index.js'), out);
  console.log(`manifest: ${stubs.length} lessons`);
}
main();
